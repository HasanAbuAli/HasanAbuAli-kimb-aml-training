# -----------------------------------
# SESSION STATE
# -----------------------------------

if "current_question" not in st.session_state:
    st.session_state.current_question = 0

if "score" not in st.session_state:
    st.session_state.score = 0

if "answered" not in st.session_state:
    st.session_state.answered = False

if "selected_answer" not in st.session_state:
    st.session_state.selected_answer = None


# -----------------------------------
# QUIZ
# -----------------------------------

total_questions = len(questions)
current = st.session_state.current_question
question = questions[current]

st.progress(current / total_questions)

st.write(
    f"### السؤال {current + 1} من {total_questions}"
)

st.caption(
    "الموضوع: " + question["category"]
)

st.subheader(
    question["question"]
)

selected = st.radio(
    "اختر الإجابة الصحيحة:",
    question["options"],
    index=None,
    key=f"question_{current}"
)


# -----------------------------------
# SUBMIT
# -----------------------------------

if st.button(
    "إرسال الإجابة ✅",
    disabled=st.session_state.answered
):

    if selected is None:
        st.warning(
            "⚠️ يرجى اختيار إجابة أولاً."
        )

    else:
        st.session_state.selected_answer = selected
        st.session_state.answered = True

        if selected == question["answer"]:
            st.session_state.score += 1


# -----------------------------------
# ANSWER RESULT
# -----------------------------------

if st.session_state.answered:

    if st.session_state.selected_answer == question["answer"]:

        st.success(
            "✅ إجابة صحيحة!"
        )

    else:

        st.error(
            "❌ إجابة غير صحيحة."
        )

        st.write(
            "**الإجابة الصحيحة:** "
            + question["answer"]
        )

    st.info(
        "💡 " + question["explanation"]
    )

    st.write(
        f"### نتيجتك الحالية: {st.session_state.score} / {current + 1}"
    )


    # NEXT QUESTION
    if current < total_questions - 1:

        if st.button(
            "السؤال التالي ➡️"
        ):

            st.session_state.current_question += 1
            st.session_state.answered = False
            st.session_state.selected_answer = None

            st.rerun()


    # FINAL RESULT
    else:

        percentage = (
            st.session_state.score
            / total_questions
        ) * 100

        st.success(
            "🏁 تم الانتهاء من الاختبار"
        )

        st.write(
            f"## النتيجة النهائية: {st.session_state.score} / {total_questions}"
        )

        st.write(
            f"## النسبة: {percentage:.0f}%"
        )

        if percentage >= 80:

            st.success(
                "🌟 ممتاز - تم اجتياز الاختبار بنجاح."
            )

        elif percentage >= 60:

            st.warning(
                "👍 نتيجة جيدة، ولكن يوصى بمراجعة بعض المواضيع."
            )

        else:

            st.error(
                "📚 يوصى بمراجعة مواد AML/CFT والعقوبات وإعادة الاختبار."
            )


# -----------------------------------
# RESTART
# -----------------------------------

st.divider()

if st.button(
    "🔄 إعادة الاختبار"
):

    st.session_state.current_question = 0
    st.session_state.score = 0
    st.session_state.answered = False
    st.session_state.selected_answer = None

    st.rerun()
